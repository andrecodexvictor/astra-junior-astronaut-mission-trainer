#!/usr/bin/env python3
"""Render the v3 pitch content with localized art and the current ASTRA branding.

Requires the project checkout and the sibling astra-institutional checkout.
Use --art-dir and --brand-svg to override their default locations.
"""
import argparse
import importlib.util
import subprocess
import tempfile
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
WORKSPACE = ROOT.parents[1]
DEFAULT_ART = WORKSPACE / 'sites/astra-institutional/art/english'
DEFAULT_BRAND = WORKSPACE / 'sites/astra-institutional/dist/assets/brand/astra-lockup-dark.svg'
URL = 'https://astra-junior-mission-trainer.vercel.app/'


def load_renderer():
    """Apply narrowly scoped presentation changes without modifying the v3 source."""
    path = ROOT / 'scripts/build-pitch-v3.py'
    source = path.read_text(encoding='utf8')
    changes = [
        ("URL='https://astra-mission-trainer.andrevictorandrade.chatgpt.site'", f"URL={URL!r}"),
        ("elif n.startswith(ALLOWED): p=PROD/n", "elif n.startswith(ALLOWED): p=ART_DIR/(Path(n).stem+'-en.png')"),
        ("text(90,65,1500,'ASTRA   /   '+stage,22,CYAN,True)", "e.append(('picture',90,45,130,55,str(BRAND_PNG)))\n    text(245,65,1350,'/   '+stage,22,CYAN,True)"),
        ("('CURRENT DEMO  ·  PREPARED SCENE' if lang=='en' else 'DEMO ATUAL  ·  CENA PREPARADA') if is_demo else ('PRODUCTION VISION  ·  AI-ASSISTED CONCEPT ART' if lang=='en' else 'VISÃO DE PRODUÇÃO  ·  ARTE CONCEITUAL COM IA')", "'Actual prototype capture · original Portuguese interface' if is_demo else 'GENERATED BY SI · AI-GENERATED CONCEPT ART'"),
        ("label='PRODUCTION VISION  ·  AI-ASSISTED CONCEPT ART' if lang=='en' else 'VISÃO DE PRODUÇÃO  ·  ARTE CONCEITUAL COM IA'", "label='GENERATED BY SI · AI-GENERATED CONCEPT ART'"),
        ('https://astra-mission-trainer.andrevictorandrade.chatgpt.site', URL),
    ]
    for old, new in changes:
        if old not in source:
            raise RuntimeError(f'v3 renderer changed; cannot apply adapter: {old[:80]}')
        source = source.replace(old, new)
    spec = importlib.util.spec_from_loader('astra_pitch_v4_renderer', loader=None)
    module = importlib.util.module_from_spec(spec)
    module.__file__ = str(path)
    exec(compile(source, str(path), 'exec'), module.__dict__)
    return module


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--art-dir', type=Path, default=DEFAULT_ART)
    parser.add_argument('--brand-svg', type=Path, default=DEFAULT_BRAND)
    parser.add_argument('--output-dir', type=Path, default=WORKSPACE / 'artifacts/ASTRA-Project-Package-2026-11-15/decks')
    args = parser.parse_args()
    if not args.brand_svg.is_file():
        parser.error(f'Brand SVG not found: {args.brand_svg}; provide --brand-svg')
    renderer = load_renderer()
    renderer.ART_DIR = args.art_dir.resolve()
    with tempfile.TemporaryDirectory(prefix='astra-brand-') as tmp:
        renderer.BRAND_PNG = Path(tmp) / 'logo.png'
        subprocess.run(['inkscape', str(args.brand_svg), '--export-filename='+str(renderer.BRAND_PNG), '--export-width=520'], check=True, capture_output=True)
        # The v3 raster compositor flattens alpha; provide a matching dark field.
        logo = Image.open(renderer.BRAND_PNG).convert('RGBA')
        field = Image.new('RGBA', logo.size, '#081522')
        Image.alpha_composite(field, logo).convert('RGB').save(renderer.BRAND_PNG)
        for filename, folder, slug in [('PITCH_EN.json','pitch-en','ASTRA-Pitch-EN-180s'), ('ELEVATOR_PT.json','elevator-pt','ASTRA-Elevator-PT-30s')]:
            renderer.build(ROOT/'docs/presentation/v3'/filename, args.output_dir/folder, slug)

if __name__ == '__main__':
    main()
